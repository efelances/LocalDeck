def list_templates() -> list[dict[str, Any]]:
    """Return lightweight metadata for all curated templates."""
    return [
        {
            "id": item["id"],
            "skin": item["skin"],
            "rows": item["rows"],
            "cols": item["cols"],
            "match_executables": item["match_executables"],
            "match_title_contains": item["match_title_contains"],
            "name": item["name"],
            "name_i18n": item["name_i18n"],
            "description_i18n": item["description_i18n"],
        }
        for item in _TEMPLATE_DEFS
    ]


def build_template_page(template_id: str) -> DeckPage | None:
    """Build a fresh validated `DeckPage` instance from a template id."""
    for item in _TEMPLATE_DEFS:
        if item["id"] == template_id:
            return item["builder"]()
    return None
