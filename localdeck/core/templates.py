from __future__ import annotations

from typing import Any

from localdeck.models import ButtonAction, DeckButton, DeckPage, PageSkin


def _btn(
    button_id: str,
    row: int,
    col: int,
    label: str,
    label_i18n: dict[str, str],
    icon: str,
    action: ButtonAction,
    tone: str = "default",
) -> DeckButton:
    return DeckButton(
        id=button_id,
        row=row,
        col=col,
        label=label,
        label_i18n=label_i18n,
        icon=icon,
        tone=tone,  # type: ignore[arg-type]
        action=action,
    )


def _page(
    template_id: str,
    name: str,
    name_i18n: dict[str, str],
    skin: PageSkin,
    rows: int,
    cols: int,
    match_executables: list[str],
    match_title_contains: list[str],
    buttons: list[DeckButton],
    audio_viz_enabled: bool = False,
) -> DeckPage:
    return DeckPage(
        id=template_id,
        name=name,
        name_i18n=name_i18n,
        skin=skin,
        audio_viz_enabled=audio_viz_enabled,
        rows=rows,
        cols=cols,
        match_executables=match_executables,
        match_title_contains=match_title_contains,
        buttons=buttons,
    )


